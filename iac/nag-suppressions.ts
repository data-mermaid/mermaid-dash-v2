/**
 * Centralized cdk-nag acknowledgments (suppressions) for all stacks.
 *
 * Each acknowledgment documents the reason and whether the finding is:
 *   - ACCEPTED: The current configuration is intentional and appropriate.
 *   - TODO: Should be addressed in a future ticket.
 */
import * as cdk from 'aws-cdk-lib'
import { Validations } from 'aws-cdk-lib'
import { IConstruct } from 'constructs'

const ACCEPTED = 'ACCEPTED'
const TODO = 'TODO'

interface NagAcknowledgment {
  id: string
  reason: string
  // Granular findings, e.g. 'Action::s3:List*'. Each becomes its own `id[finding]` acknowledgment.
  appliesTo?: string[]
}

// cdk-nag v3 acknowledges one rule per call and matches granular findings by the exact
// `RuleId[finding]` string (no regex), so expand appliesTo into one call per finding.
function acknowledge(scope: IConstruct, acknowledgments: NagAcknowledgment[]): void {
  for (const { id, reason, appliesTo } of acknowledgments) {
    const ruleIds = appliesTo ? appliesTo.map((finding) => `${id}[${finding}]`) : [id]
    for (const ruleId of ruleIds) {
      Validations.of(scope).acknowledge({ id: ruleId, reason })
    }
  }
}

export function applyNagSuppressions(stack: cdk.Stack): void {
  // cdk-nag flattens an unresolved account/region (e.g. synth without CDK_DEFAULT_ACCOUNT)
  // to these markers; a raw token here would also break synth, as acknowledgment IDs must be strings.
  const account = cdk.Token.isUnresolved(stack.account) ? '<AWS::AccountId>' : stack.account
  const region = cdk.Token.isUnresolved(stack.region) ? '<AWS::Region>' : stack.region

  acknowledge(stack, [
    // --- S3 ---
    {
      id: 'AwsSolutions-S1',
      reason: `${TODO}: Enable server access logging on the site bucket.`,
    },
    {
      id: 'AwsSolutions-S10',
      reason: `${TODO}: Enforce HTTPS-only access via aws:SecureTransport condition.`,
    },

    // --- CloudFront ---
    {
      id: 'AwsSolutions-CFR1',
      reason: `${ACCEPTED}: MERMAID is a global marine-data platform; geo restrictions are not appropriate.`,
    },
    {
      id: 'AwsSolutions-CFR2',
      reason: `${TODO}: Evaluate adding AWS WAF integration.`,
    },
    {
      id: 'AwsSolutions-CFR3',
      reason: `${TODO}: Enable CloudFront access logging.`,
    },
    {
      id: 'AwsSolutions-CFR7',
      reason: `${TODO}: Migrate from Origin Access Identity (OAI) to Origin Access Control (OAC).`,
    },

    // --- IAM ---
    {
      id: 'AwsSolutions-IAM4',
      reason: `${ACCEPTED}: AWSLambdaBasicExecutionRole is the standard CDK-managed policy for BucketDeployment Lambda logging.`,
      appliesTo: [
        'Policy::arn:<AWS::Partition>:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole',
      ],
    },
    {
      id: 'AwsSolutions-IAM5',
      reason: `${ACCEPTED}: Wildcard actions/resources are generated by CDK BucketDeployment grant helpers; scoped to the specific site bucket and CDK assets bucket. Resource::* is required for CloudFront invalidation APIs which do not support resource-level permissions.`,
      appliesTo: [
        'Action::s3:GetBucket*',
        'Action::s3:GetObject*',
        'Action::s3:List*',
        'Action::s3:Abort*',
        'Action::s3:DeleteObject*',
        // v2 matched these two with regexes; v3 needs the exact strings.
        'Resource::<StaticSiteBucket9C756C46.Arn>/*',
        `Resource::arn:aws:s3:::cdk-${cdk.DefaultStackSynthesizer.DEFAULT_QUALIFIER}-assets-${account}-${region}/*`,
        'Resource::*',
      ],
    },

    // --- Lambda ---
    {
      id: 'AwsSolutions-L1',
      reason: `${ACCEPTED}: BucketDeployment Lambda runtime is CDK-managed; auto-updated on CDK upgrades.`,
    },
  ])
}
